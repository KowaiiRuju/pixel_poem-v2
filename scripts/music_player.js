document.addEventListener("DOMContentLoaded", () => {
  const audio = document.getElementById("audio");
  const playPauseBtn = document.getElementById("play-pause");
  const prevBtn = document.getElementById("prev");
  const nextBtn = document.getElementById("next");
  const minimizeBtn = document.getElementById("minimize-btn");
  const trackTitle = document.getElementById("track-title");
  const player = document.getElementById("music-player");
  const queueDiv = document.getElementById("music-queue");
  const progressWrapper = document.getElementById("progress-wrapper");
  const progressBar = document.getElementById("progress-bar");
  const progressThumb = document.getElementById("progress-thumb");
  const currentTimeEl = document.getElementById("current-time");
  const durationTimeEl = document.getElementById("duration-time");
  const muteBtn = document.getElementById("mute-btn");
  const volumeSlider = document.getElementById("volume-slider");
  const headerStatusBadge = document.getElementById("player-nav-status");
  const headerEqualizer = document.querySelector(".equalizer");
  const headerNowPlaying = document.getElementById("nav-now-playing");

  // Playlist (auto-generated by download_songs.py)
  const playlist = [
    { title: "Kitchie Nadal - Same Ground", src: "playlist/01 - Kitchie Nadal - Same Ground.mp3" },
    { title: "Eve × suis from Yorushika - 平行線 (Heikousen)", src: "playlist/02 - Eve × suis from Yorushika - 平行線 (Heikousen).mp3" },
    { title: "YOASOBI - たぶん (Tabun)", src: "playlist/03 - YOASOBI - たぶん (Tabun).mp3" },
    { title: "Lola Amour - Fallen", src: "playlist/04 - Lola Amour - Fallen.mp3" },
    { title: "Yorushika (ヨルシカ) - Sunny (晴る / Haru)", src: "playlist/05 - Yorushika (ヨルシカ) - Sunny (晴る _ Haru).mp3" },
    { title: "Janine Berdin - What if I miss you for the rest of my life?", src: "playlist/06 - Janine Berdin - What if I miss you for the rest of my life_.mp3" },
    { title: "Mariah Deborah - Na Para Bang", src: "playlist/07 - Mariah Deborah - Na Para Bang.mp3" },
  ];

  let currentTrack = 0;
  let isSeeking = false;

  // Format seconds into M:SS
  function formatTime(sec) {
    if (isNaN(sec) || sec < 0) return "0:00";
    const minutes = Math.floor(sec / 60);
    const seconds = Math.floor(sec % 60);
    return `${minutes}:${seconds < 10 ? "0" : ""}${seconds}`;
  }

  const stopBtn = document.getElementById("stop-btn");
  const deckPlayIcon = document.getElementById("deck-play-icon");
  const deckPlayLabel = document.getElementById("deck-play-label");
  const deckMuteIcon = document.getElementById("deck-mute-icon");

  function updatePlayPauseIcons(isPlaying) {
    if (playPauseBtn) {
      const icon = playPauseBtn.querySelector(".material-icons");
      if (icon) icon.textContent = isPlaying ? "pause_circle" : "play_circle";
      if (isPlaying) {
        playPauseBtn.classList.add("pressed");
      } else {
        playPauseBtn.classList.remove("pressed");
      }
    }
    if (deckPlayIcon) {
      deckPlayIcon.className = isPlaying ? "fa-solid fa-pause" : "fa-solid fa-play";
    }
    if (deckPlayLabel) {
      deckPlayLabel.textContent = isPlaying ? "PAUS" : "PLAY";
    }
    const quickPlayBtn = document.getElementById("quick-play");
    if (quickPlayBtn) {
      const quickIcon = quickPlayBtn.querySelector(".material-icons");
      if (quickIcon) quickIcon.textContent = isPlaying ? "pause" : "play_arrow";
    }
    const cassetteBody = document.getElementById("cassetteBody");
    if (cassetteBody) {
      if (isPlaying) {
        cassetteBody.classList.add("playing");
      } else {
        cassetteBody.classList.remove("playing");
      }
    }
    if (headerEqualizer) {
      if (isPlaying) {
        headerEqualizer.classList.add("playing");
      } else {
        headerEqualizer.classList.remove("playing");
      }
    }
  }

  function loadTrack(index) {
    currentTrack = (index + playlist.length) % playlist.length;
    const track = playlist[currentTrack];
    audio.src = track.src;
    
    if (trackTitle) {
      trackTitle.textContent = `${track.title}`;
      trackTitle.title = track.title;
    }
    const cassetteName = document.getElementById("cassetteName");
    if (cassetteName) {
      cassetteName.textContent = track.title;
      cassetteName.title = track.title;
    }
    if (headerNowPlaying) {
      headerNowPlaying.textContent = track.title;
    }

    // Reset progress displays
    if (progressBar) progressBar.style.width = "0%";
    if (progressThumb) progressThumb.style.left = "0%";
    if (currentTimeEl) currentTimeEl.textContent = "0:00";
    if (durationTimeEl) durationTimeEl.textContent = "0:00";

    audio.load();
    document.title = `Now Playing: ${track.title}`;
    renderQueue();
  }

  function renderQueue() {
    if (!queueDiv) return;
    if (player && player.classList.contains("collapsed")) {
      queueDiv.style.display = "none";
      return;
    }
    let html = '<ul>';
    playlist.forEach((track, i) => {
      const isActive = (i === currentTrack);
      const activeClass = isActive ? 'active' : '';
      const icon = isActive ? '<span class="material-icons" style="font-size:1.1rem;color:#ff4081;">play_arrow</span>' : '<span style="opacity:0.4;">•</span>';
      html += `<li class="queue-item ${activeClass}" data-index="${i}" title="${track.title}">
        <span class="queue-item-icon">${icon}</span>
        <span style="overflow:hidden;text-overflow:ellipsis;">${track.title}</span>
      </li>`;
    });
    html += '</ul>';
    queueDiv.innerHTML = html;
    queueDiv.style.display = "block";

    // Direct click to play from queue
    queueDiv.querySelectorAll('.queue-item').forEach(item => {
      item.addEventListener('click', () => {
        const idx = parseInt(item.getAttribute('data-index'), 10);
        if (!isNaN(idx)) {
          loadTrack(idx);
          audio.play().then(() => updatePlayPauseIcons(true)).catch(() => {});
        }
      });
    });
  }

  // Play / Pause Toggle
  if (playPauseBtn) {
    playPauseBtn.addEventListener("click", () => {
      if (audio.paused) {
        audio.play().then(() => updatePlayPauseIcons(true)).catch(err => {
          console.warn("Audio autoplay blocked by browser policy:", err);
        });
      } else {
        audio.pause();
        updatePlayPauseIcons(false);
      }
      playPauseBtn.blur();
    });
  }

  // Quick Play / Pause for Collapsed Cassette
  const quickPlayBtn = document.getElementById("quick-play");
  if (quickPlayBtn) {
    quickPlayBtn.addEventListener("click", () => {
      if (playPauseBtn) playPauseBtn.click();
      quickPlayBtn.blur();
    });
  }

  // Tap Cassette Tape Directly to Play / Pause
  const cassetteBodyEl = document.getElementById("cassetteBody");
  if (cassetteBodyEl) {
    cassetteBodyEl.addEventListener("click", (e) => {
      if (e.target.closest("button") || e.target.closest("a")) return;
      if (playPauseBtn) playPauseBtn.click();
    });
  }

  // Previous Track
  if (prevBtn) {
    prevBtn.addEventListener("click", () => {
      loadTrack(currentTrack - 1);
      audio.play().then(() => updatePlayPauseIcons(true)).catch(() => {});
      prevBtn.blur();
    });
  }

  // Next Track
  if (nextBtn) {
    nextBtn.addEventListener("click", () => {
      loadTrack(currentTrack + 1);
      audio.play().then(() => updatePlayPauseIcons(true)).catch(() => {});
      nextBtn.blur();
    });
  }

  // Audio Events
  audio.addEventListener("play", () => updatePlayPauseIcons(true));
  audio.addEventListener("pause", () => updatePlayPauseIcons(false));
  audio.addEventListener("ended", () => {
    loadTrack(currentTrack + 1);
    audio.play().then(() => updatePlayPauseIcons(true)).catch(() => {});
  });

  // Time & Progress Updates
  audio.addEventListener("timeupdate", () => {
    if (isSeeking) return;
    if (audio.duration) {
      const progressPercent = (audio.currentTime / audio.duration) * 100;
      if (progressBar) progressBar.style.width = `${progressPercent}%`;
      if (progressThumb) progressThumb.style.left = `${progressPercent}%`;
      if (currentTimeEl) currentTimeEl.textContent = formatTime(audio.currentTime);
    }
  });

  audio.addEventListener("loadedmetadata", () => {
    if (durationTimeEl && audio.duration) {
      durationTimeEl.textContent = formatTime(audio.duration);
    }
  });

  // Scrubber Seeking
  if (progressWrapper) {
    function seek(e) {
      const rect = progressWrapper.getBoundingClientRect();
      const clickX = Math.max(0, Math.min(e.clientX - rect.left, rect.width));
      const percentage = clickX / rect.width;
      if (audio.duration) {
        audio.currentTime = percentage * audio.duration;
        if (progressBar) progressBar.style.width = `${percentage * 100}%`;
        if (progressThumb) progressThumb.style.left = `${percentage * 100}%`;
        if (currentTimeEl) currentTimeEl.textContent = formatTime(audio.currentTime);
      }
    }

    progressWrapper.addEventListener("mousedown", (e) => {
      isSeeking = true;
      seek(e);
      function onMouseMove(moveEvent) {
        seek(moveEvent);
      }
      function onMouseUp() {
        isSeeking = false;
        window.removeEventListener("mousemove", onMouseMove);
        window.removeEventListener("mouseup", onMouseUp);
      }
      window.addEventListener("mousemove", onMouseMove);
      window.addEventListener("mouseup", onMouseUp);
    });

    // Touch support for scrubber
    progressWrapper.addEventListener("touchstart", (e) => {
      if (e.touches.length > 0) {
        isSeeking = true;
        const touch = e.touches[0];
        seek({ clientX: touch.clientX });
      }
    }, { passive: true });

    progressWrapper.addEventListener("touchmove", (e) => {
      if (isSeeking && e.touches.length > 0) {
        const touch = e.touches[0];
        seek({ clientX: touch.clientX });
      }
    }, { passive: true });

    progressWrapper.addEventListener("touchend", () => {
      isSeeking = false;
    });
  }

  // Volume & Mute
  if (volumeSlider) {
    volumeSlider.addEventListener("input", (e) => {
      const val = parseFloat(e.target.value);
      audio.volume = val;
      audio.muted = (val === 0);
      if (muteBtn) {
        const icon = muteBtn.querySelector(".material-icons");
        if (icon) icon.textContent = (val === 0) ? "volume_off" : "volume_up";
      }
    });
  }

  if (stopBtn) {
    stopBtn.addEventListener("click", () => {
      audio.pause();
      audio.currentTime = 0;
      updatePlayPauseIcons(false);
      stopBtn.blur();
    });
  }

  if (muteBtn) {
    muteBtn.addEventListener("click", () => {
      audio.muted = !audio.muted;
      const icon = muteBtn.querySelector(".material-icons");
      if (icon) icon.textContent = audio.muted ? "volume_off" : "volume_up";
      if (deckMuteIcon) {
        deckMuteIcon.className = audio.muted ? "fa-solid fa-volume-xmark" : "fa-solid fa-volume-high";
      }
      if (audio.muted) {
        muteBtn.classList.add("pressed");
      } else {
        muteBtn.classList.remove("pressed");
      }
      if (!audio.muted && volumeSlider && audio.volume === 0) {
        audio.volume = 0.5;
        volumeSlider.value = 0.5;
      }
    });
  }

  // Minimize / Expand
  if (minimizeBtn) {
    minimizeBtn.addEventListener("click", () => {
      if (player) {
        player.classList.toggle("collapsed");
        minimizeBtn.blur();
        renderQueue();
      }
    });
  }

  // Header status badge clicks toggle player expand/collapse
  if (headerStatusBadge) {
    headerStatusBadge.addEventListener("click", () => {
      if (player) {
        player.classList.remove("collapsed");
        renderQueue();
      }
    });
  }

  // Keyboard accessibility
  document.addEventListener("keydown", (e) => {
    // Avoid interfering when typing in inputs/dialogs
    if (["INPUT", "TEXTAREA"].includes(document.activeElement.tagName)) return;
    if (e.code === "Space") {
      e.preventDefault();
      if (playPauseBtn) playPauseBtn.click();
    } else if (e.code === "ArrowRight" && e.altKey) {
      if (nextBtn) nextBtn.click();
    } else if (e.code === "ArrowLeft" && e.altKey) {
      if (prevBtn) prevBtn.click();
    }
  });

  // Initial load
  loadTrack(currentTrack);

  // On mobile screens, start collapsed as a docked cassette pill for unobstructed poem reading
  if (window.innerWidth <= 768 && player) {
    player.classList.add("collapsed");
    renderQueue();
  }
});
